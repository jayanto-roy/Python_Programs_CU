str1 = "Hello"
str2 = "Python"

# Concatenation
print("Concatenation:", str1 + " " + str2)

# Repetition
print("Repetition:", str1 * 3)

# Indexing
print("First character:", str2[0])
print("Last character:", str2[-1])

# Slicing
print("First three characters:", str2[0:3])
print("Last three characters:", str2[-3:])